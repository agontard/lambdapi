(** Translate parser-level Lambdapi commands to Rocq.

There are two modes:

- raw_coq: translation of commands as they are

- stt_coq: translation of commands modulo an encoding of simple type theory
specified through a lambdapi file with the option --encoding. A map giving the
number of type variables of each function symbol can be given as a .tvs file
(as generated by hol2dk) with the option --arities.

In both modes, a renaming map can be provided with the option --renaming to
rename some identifiers. *)

open Lplib open Extra
open Common open Pos open Error
open Parsing open Syntax
open Stt

(** Valid Rocq identifiers (excluding unicode characters). *)

let is_valid_first_letter =
  function 'a'..'z' | 'A'..'Z' | '_' -> true | _ -> false
let is_valid_letter =
  function 'a'..'z' | 'A'..'Z' | '_' | '0'..'9' | '\'' -> true | _ -> false
let is_valid_rocq_id s =
  s <> "" && is_valid_first_letter s.[0] && String.for_all is_valid_letter s

let _ =
  Stt.check := fun pos s ->
    if not (is_valid_rocq_id s) then fatal pos "invalid Rocq identifier"

(** Translation of terms. *)

let rec term oc t =
  (*if Logger.log_enabled() then
    log "pp %a" (*Pos.short t.pos*) Pretty.term t;*)
  match t.elt with
  | P_Meta _ -> wrn t.pos "TODO"; assert false
  | P_Patt _ -> wrn t.pos "TODO"; assert false
  | P_Expl _ -> wrn t.pos "TODO"; assert false
  | P_SLit _ -> wrn t.pos "TODO"; assert false
  | P_NLit _ -> wrn t.pos "TODO"; assert false
  | P_Type -> string oc "Type"
  | P_Wild -> char oc '_'
  | P_Iden(qid,b) -> if b then char oc '@'; qident oc qid
  | P_Arro(u,v) -> arrow oc u v
  | P_Abst(xs,u) -> abst oc xs u
  | P_Prod(xs,u) -> prod oc xs u
  | P_LLet(x,xs,a,u,v) ->
    string oc "let "; ident oc x; params_list oc xs; typopt oc a;
    string oc " := "; term oc u; string oc " in "; term oc v
  | P_Wrap u -> term oc u
  | P_Appl _ -> app oc false t

and app oc =
  let default h ts = paren oc h ; char oc ' ' ; list paren " " oc ts in
  Stt.app (string oc) (term oc) (paren oc) (ne_params_list oc) default
and arrow oc u v = paren oc u; string oc " -> "; term oc v
and abst oc xs u =
  string oc "fun"; params_list_in_abs oc xs; string oc " => "; term oc u
and prod oc xs u =
  string oc "forall"; params_list_in_abs oc xs; string oc ", "; term oc u

and paren oc t =
  let default () = char oc '('; term oc t; char oc ')' in
  match unwrap t.elt with
  | P_Arro _ | P_Abst _ | P_Prod _ | P_LLet _ | P_Wrap _-> default()
  | P_Appl _ -> app oc true t
  | _ -> term oc t

and raw_params oc (ids,t,_) = param_ids oc ids; typopt oc t

and params oc ((ids,t,b) as x) =
  match b, t with
  | true, _ -> char oc '{'; raw_params oc x; char oc '}'
  | false, Some _ -> char oc '('; raw_params oc x; char oc ')'
  | false, None -> param_ids oc ids

(* starts with a space if the list is not empty *)
and params_list oc = List.iter (prefix " " params oc)

(* starts with a space if the list is not empty *)
and params_list_in_abs oc l =
  match l with
  | [ids,t,false] -> char oc ' '; param_ids oc ids; typopt oc t
  | _ -> params_list oc l

(* Considers a space to already be written if needed. Must be non-empty *)
and ne_params_list oc l =
  match l with
  | [ids,t,false] -> param_ids oc ids; typopt oc t
  | p :: l -> params oc p ; params_list oc l
  | _ -> assert false
(* starts with a space if <> None *)
and typopt oc t = Option.iter (prefix " : " term oc) t

(** Translation of commands. *)

let pqid_of_pid {elt; pos} = {elt=([],elt); pos}

let add_modifier oc name (md : p_modifier) =
  let prefix = match md.elt with
  | P_opaq -> Some "Opaque "
  | P_typeclass -> Some "Existing Class "
  | P_typeclass_instance -> Some "Existing Instance "
  | _ -> None
  in
  let with_prefix prefix =
    string oc prefix; qident oc name; string oc ".\n"
  in
  Option.iter with_prefix prefix

let command oc {elt; pos} =
  begin match elt with
  | P_open(_,true,ps) ->
      string oc "Import "; list path " " oc ps; string oc ".\n"
  | P_open(_,false,ps) ->
      string oc "Export "; list path " " oc ps; string oc ".\n"
  | P_require (None, ps) ->
      string oc "Require "; list path " " oc ps; string oc ".\n"
  | P_require (Some true, ps) ->
      string oc "Require Import "; list path " " oc ps; string oc ".\n"
  | P_require (Some false, ps) ->
      string oc "Require Export "; list path " " oc ps; string oc ".\n"
  | P_require_as (p,i) ->
    Stt.alias := StrMap.add i.elt p.elt !Stt.alias;
    string oc "Module "; ident oc i; string oc " := "; path oc p;
    string oc ".\n"
  | P_symbol
    { p_sym_mod; p_sym_kw=_; p_sym_nam; p_sym_arg; p_sym_typ;
      p_sym_trm; p_sym_prf=_; p_sym_def } ->
      if not (is_mapped p_sym_nam.elt)
      then let modifiers =
        match p_sym_def, p_sym_trm, p_sym_arg, p_sym_typ with
        | true, Some t, _, Some a when List.exists is_lem p_sym_mod ->
          (* If they have a type, opaque or private defined symbols are
             translated as Lemma's so that their definition is loaded in
             memory only when it is necessary. *)
          let mods_left = List.filter (fun m -> not (is_lem m)) p_sym_mod in
          let res =
            List.filter (fun {elt;_} -> elt != P_typeclass) mods_left in
          let prefix = if res == mods_left then "Lemma " else "Instance " in
          string oc prefix ; ident oc p_sym_nam; params_list oc p_sym_arg;
          string oc " : "; term oc a; string oc ".\nProof. exact (";
          term oc t; string oc "). Qed.\n";
          res
        | true, Some t, _, _ ->
          let res =
            List.filter (fun {elt;_} -> elt != P_typeclass) p_sym_mod in
          let prefix = if res == p_sym_mod || Option.is_none p_sym_typ
            then "Definition " else "Instance " in
          string oc prefix ; ident oc p_sym_nam;
          params_list oc p_sym_arg; typopt oc p_sym_typ;
          string oc " := "; term oc t; string oc ".\n";
          res
        | false, _, [], Some t ->
          string oc "Axiom "; ident oc p_sym_nam; string oc " : ";
          term oc t; string oc ".\n";
          p_sym_mod
        | false, _, _, Some t ->
          string oc "Axiom "; ident oc p_sym_nam; string oc " : forall";
          params_list oc p_sym_arg; string oc ", "; term oc t;
          string oc ".\n";
          p_sym_mod
        | _ -> wrn pos "Command not translated."; []
      in List.iter (add_modifier oc (pqid_of_pid p_sym_nam)) modifiers
  | P_opaque qid -> add_modifier oc qid {elt=P_opaq;pos}
  | P_type_class qid -> add_modifier oc qid {elt=P_typeclass;pos}
  | P_type_class_instance qid ->
    add_modifier oc qid {elt=P_typeclass_instance;pos}
  | _ -> wrn pos "Command not translated."
  end

let commands oc = Stream.iter (command oc)

(** Set Coq required file. *)

let print : p_commands -> unit = fun cs ->
  let oc = stdout in
  begin match !require with
  | Some f -> string oc ("Require Import "^f^".\n")
  | None -> ()
  end;
  commands oc cs
